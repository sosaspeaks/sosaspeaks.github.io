CREATE TABLE IF NOT EXISTS public.lyric_cards (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  spin_id BIGINT NULL REFERENCES public.spins(id) ON DELETE SET NULL,
  artist_name TEXT NOT NULL,
  song_title TEXT NOT NULL,
  album_title TEXT NULL,
  release_year INTEGER NULL,
  cover_url TEXT NULL,
  lyrics TEXT NOT NULL,
  tags TEXT[] NOT NULL DEFAULT '{}',
  card_theme TEXT NOT NULL DEFAULT 'cover-blur'
    CHECK (card_theme IN (
      'cover-blur',
      'aero-glass',
      'terminal-mono',
      'editorial-paper',
      'jewel-case',
      'dreamcore-sky',
      'midnight-vinyl',
      'prism-mesh',
      'swatch-poster',
      'oscilloscope',
      'cassette-jcard',
      'kinetic-grid',
      'refraction'
    )),
  color_scheme TEXT NOT NULL DEFAULT 'cover'
    CHECK (color_scheme IN ('cover', 'emerald', 'cobalt', 'amber', 'rose', 'mono')),
  aspect_ratio TEXT NOT NULL DEFAULT '4:5'
    CHECK (aspect_ratio IN ('4:5', '1:1')),
  accent_color TEXT NULL,
  element_sizes JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Safe upgrades if table was created prior to adding element_sizes, color_scheme, or new themes
ALTER TABLE public.lyric_cards
  ADD COLUMN IF NOT EXISTS element_sizes JSONB NOT NULL DEFAULT '{}'::jsonb;

ALTER TABLE public.lyric_cards
