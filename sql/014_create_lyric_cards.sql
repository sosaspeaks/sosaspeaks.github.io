CREATE INDEX IF NOT EXISTS idx_lyric_cards_tags
  ON public.lyric_cards USING GIN (tags);

CREATE INDEX IF NOT EXISTS idx_lyric_cards_created_at
  ON public.lyric_cards (created_at DESC, id DESC);

