CREATE TABLE IF NOT EXISTS public.sosa_core_tags (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  description TEXT NOT NULL DEFAULT '',
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.sosa_core (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  spin_id BIGINT NULL REFERENCES public.spins(id) ON DELETE SET NULL,
  artist TEXT NOT NULL,
  title TEXT NOT NULL,
  release_year INTEGER NULL,
  cover_url TEXT NOT NULL DEFAULT 'assets/images/spins/placeholder.png',
  rating NUMERIC(2,1) NULL,
  genres TEXT[] NOT NULL DEFAULT '{}',
  secondary_genres TEXT[] NOT NULL DEFAULT '{}',
  slot_type TEXT NOT NULL DEFAULT 'standard'
    CHECK (slot_type IN ('cornerstone', 'liner_note', 'genre', 'standard')),
  tags TEXT[] NOT NULL DEFAULT '{}',
  liner_note TEXT NULL,
  position INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_sosa_core_position ON public.sosa_core (position ASC, id ASC);
CREATE INDEX IF NOT EXISTS idx_sosa_core_tags_order ON public.sosa_core_tags (sort_order ASC, id ASC);

GRANT USAGE ON SCHEMA public TO anon, authenticated;
GRANT SELECT ON TABLE public.sosa_core_tags, public.sosa_core TO anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.sosa_core_tags, public.sosa_core TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.sosa_core_tags_id_seq, public.sosa_core_id_seq TO authenticated;

ALTER TABLE public.sosa_core_tags ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sosa_core ENABLE ROW LEVEL SECURITY;

